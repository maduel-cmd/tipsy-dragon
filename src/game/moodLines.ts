const LINE_COUNT =
  MOOD_LINES.happy.length + MOOD_LINES.sad.length + MOOD_LINES.angry.length;

/** סה״כ גרסאות בקטלוג (צפוי 60) */
export function moodLineCatalogSize(): number {
  return LINE_COUNT;
}

function hashId(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** בחירה יציבה למשפט לפי לקוח + מצב רוח */
export function pickMoodLine(customerId: string, mood: CustomerMood): string {
  const pool = MOOD_LINES[mood];
  const idx = hashId(`${customerId}::${mood}`) % pool.length;
  return pool[idx]!;
}

export function moodLabelHe(mood: CustomerMood): string {
  if (mood === "happy") return "שמח";
  if (mood === "sad") return "עצוב";
  return "כועס";
}
