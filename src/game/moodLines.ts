export type CustomerMood = "happy" | "sad" | "angry";

/** ספי סבלנות: ירוק → צהוב → אדום */
export function moodFromPatienceRatio(ratio: number): CustomerMood {
  if (ratio >= 0.55) return "happy";
  if (ratio >= 0.3) return "sad";
  return "angry";
}

